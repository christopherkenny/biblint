fn alphabetic_suffix(mut number: usize) -> String {
    let mut suffix = String::new();
    while number > 0 {
        number -= 1;
        let character = char::from_u32(
            u32::from(b'a') + u32::try_from(number % 26).expect("remainder is below 26"),
        )
        .expect("alphabetic suffix is an ASCII letter");
        suffix.push(character);
        number /= 26;
    }
    suffix.chars().rev().collect()
}

